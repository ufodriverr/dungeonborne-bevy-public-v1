//! `db_pipeline items-doc`: writes from the config cache.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::Context;
use db_formats::ConfigTables;
use db_sim::SimRng;
use db_sim::items::{AffixSource, ItemDb};

const ROLLS: u32 = 10_000;
const SEED: u64 = 77;

pub fn run(cache: &Path, out: &Path) -> anyhow::Result<()> {
    let t: ConfigTables = serde_json::from_slice(
        &std::fs::read(cache.join("tables.json")).with_context(|| format!("reading {}/tables.json (run `db_pipeline config`)", cache.display()))?,
    )?;
    let strings: BTreeMap<String, BTreeMap<String, String>> = serde_json::from_slice(&std::fs::read(cache.join("strings.json"))?)?;
    let text = |k: &str| strings.values().find_map(|s| s.get(k)).cloned();
    let names: BTreeMap<i32, String> = t.excel_item_type.iter().map(|i| (i.type_id, i.name.clone())).collect();
    let db = ItemDb::new(&t)?;
    let mut rng = SimRng::new(SEED);
    let by_rarity = db.by_rarity();
    let no_rarity = db.item_ids().len() - by_rarity.values().map(Vec::len).sum::<usize>();

    let mut md = String::new();
    writeln!(md, "# Items and affixes")?;
    writeln!(md)?;
    writeln!(md, "Generated by `cargo run -p db_pipeline -- items-doc` (task S7). Code: `crates/db_sim/src/items.rs`; test: `crates/db_sim/tests/items.rs`.")?;
    writeln!(md)?;
    writeln!(md, "## Model")?;
    writeln!(md)?;
    writeln!(md, "**CONFIRMED (tables):**")?;
    writeln!(md, "- An item id's rarity comes from `UESourceItemType.rarity` (Rotted 1, Normal 2, Uncommon 3, Enhanced 4, Epic 5, Legendary 6, Unique 7, Exceptional 8).")?;
    writeln!(md, "- `ExcelAffixTemplate` per item: `fixed_rule` (BASIC affixes: weapon attack, gear levels, guard reduction, move-speed penalty; fixed or a min/max/unit offset) and `random_rule`s (MAJOR/MINOR), each naming a count pool and zero or more affix pools. Some pool entries carry a condition (monster or level rule).")?;
    writeln!(md, "- `ExcelAffixCountRandomPool`: weighted counts (99 = every attribute of the pool). `ExcelAffixPool`: attributes with weights.")?;
    writeln!(md, "- `ExcelAffixValueTemplate`: (value template id, attribute type) → per affix type and rarity a [min, max] range on a `unit` grid.")?;
    writeln!(md)?;
    writeln!(md, "**HYPOTHESIS (the server rolled; the port's roll code):**")?;
    writeln!(md, "- A rule with no pool rolls nothing (Rotted/Normal items have three empty MINOR rules). Unconditional pool entries are used for a plain roll; conditional ones belong to specific monster/level drops (S8).")?;
    writeln!(md, "- One pool id is picked uniformly when a rule lists several; the count is a weighted pick; attributes are drawn by weight without repeats within an item; values are uniform on the unit grid.")?;
    writeln!(md, "- Ability sets, gem slots and gear sets inside templates are not rolled yet (G3).")?;
    writeln!(md, "- **Missing minor pools:** the MINOR pools the templates name (`1002xx`, `1005xx`, `1009xx`, …) are not in the client data. Fallback (`overrides::MINOR_POOL_FALLBACK`): uniform over the attributes that have a MINOR range for the item's value template and rarity.")?;
    writeln!(md)?;
    writeln!(md, "## Seeded roll report")?;
    writeln!(md)?;
    writeln!(md, "{ROLLS} rolls per rarity (seed {SEED}), cycling through that rarity's item ids. Every rolled item passed `ItemDb::check`: each random affix has a range for its item and rarity, its value is inside it and on the grid, no attribute repeats, and pool affixes belong to their pool. {no_rarity} affix templates have no `UESourceItemType` row (no rarity), so they're not rolled.")?;
    writeln!(md)?;
    writeln!(md, "| Rarity | Item ids | Affixes per item | Fixed | From pools | Minor fallback |")?;
    writeln!(md, "|---|---:|---:|---:|---:|---:|")?;
    let mut examples = Vec::new();
    for (rarity, ids) in &by_rarity {
        let (mut fixed, mut pool, mut fb) = (0u32, 0u32, 0u32);
        for i in 0..ROLLS {
            let item = db.roll(ids[(i as usize) % ids.len()], &mut rng)?;
            db.check(&item)?;
            for a in &item.affixes {
                match a.source {
                    AffixSource::Fixed => fixed += 1,
                    AffixSource::Pool(_) => pool += 1,
                    AffixSource::MinorFallback => fb += 1,
                }
            }
            if i == 0 {
                examples.push(item);
            }
        }
        let name = db_formats::config::generated::EnItemRarity::from_number(*rarity);
        let per = f64::from(fixed + pool + fb) / f64::from(ROLLS);
        writeln!(md, "| {rarity} {name:?} | {} | {per:.2} | {fixed} | {pool} | {fb} |", ids.len())?;
    }
    writeln!(md)?;
    writeln!(md, "## Example rolls (first roll per rarity)")?;
    for item in &examples {
        let name = names.get(&item.item_id).and_then(|k| text(k)).unwrap_or_default();
        writeln!(md)?;
        writeln!(md, "**{} — {:?}** {name}", item.item_id, item.rarity)?;
        writeln!(md)?;
        for a in &item.affixes {
            writeln!(md, "- {:?} `{}` = {} ({:?})", a.kind, a.attribute, a.value, a.source)?;
        }
    }
    std::fs::write(out, md).with_context(|| format!("writing {}", out.display()))?;
    println!("items-doc: {} rarities -> {}", by_rarity.len(), out.display());
    Ok(())
}
