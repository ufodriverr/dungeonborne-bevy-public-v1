//! `db_pipeline loot-doc`: writes from the config cache.

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::path::Path;

use anyhow::Context;
use db_formats::ConfigTables;
use db_sim::SimRng;
use db_sim::loot::{LootDb, SourceKind};

const ROLLS: u32 = 10_000;
const SEED: u64 = 88;

pub fn run(cache: &Path, out: &Path) -> anyhow::Result<()> {
    let t: ConfigTables = serde_json::from_slice(
        &std::fs::read(cache.join("tables.json")).with_context(|| format!("reading {}/tables.json (run `db_pipeline config`)", cache.display()))?,
    )?;
    let strings: BTreeMap<String, BTreeMap<String, String>> = serde_json::from_slice(&std::fs::read(cache.join("strings.json"))?)?;
    let text = |k: &str| strings.values().find_map(|s| s.get(k)).cloned().unwrap_or_default();
    let item_name: BTreeMap<i32, String> = t.excel_item_type.iter().map(|i| (i.type_id, text(&i.name))).collect();
    let db = LootDb::new(&t)?;
    let mut rng = SimRng::new(SEED);

    let mut by_kind: BTreeMap<SourceKind, Vec<i32>> = BTreeMap::new();
    for id in db.source_ids() {
        if !db.has_table_loot(id) {
            by_kind.entry(db.kind(id)).or_default().push(id);
        }
    }

    let mut md = String::new();
    writeln!(md, "# Loot")?;
    writeln!(md)?;
    writeln!(md, "Generated by `cargo run -p db_pipeline -- loot-doc` (task S8). Code: `crates/db_sim/src/loot.rs`; test: `crates/db_sim/tests/loot.rs`.")?;
    writeln!(md)?;
    writeln!(md, "## What the client data has (CONFIRMED)")?;
    writeln!(md)?;
    writeln!(md, "- `ExcelLootSourceMap`: {} loot sources (actor class name → id).", db.source_ids().len())?;
    writeln!(md, "- Only **{}** sources have choose groups (`ExcelLootUeSourceChooseGroup`): four treasure chests and seven tutorial monsters. 16 group rates, 18 drop items.", db.source_ids().iter().filter(|i| db.has_table_loot(**i)).count())?;
    writeln!(md, "- `ExcelLootRarePoolItemRate`, `ExcelLootRarePoolCntLimit`, `ExcelLootUnluckyValue`, `ExcelItemMagicFound`, `ExcelLootDisableLootId`: **0 rows**. Rare pools, bad-luck protection and magic find were server-side; they are not modelled.")?;
    writeln!(md)?;
    writeln!(md, "## Roll code")?;
    writeln!(md)?;
    writeln!(md, "- Table sources (HYPOTHESIS for the reading of the rates): each loot id drops with probability `default_rate / 10000`; a random id is picked by `pr`; one drop row by `rate` weight. Items with an affix template are rolled as gear (S7); others drop as stacks.")?;
    writeln!(md, "- All other sources: classified by actor name (`loot::classify`) and rolled from `overrides::fallback_loot` (chance, item count, rarity weights). **HYPOTHESIS, placeholder numbers for playtest tuning.**")?;
    writeln!(md)?;
    writeln!(md, "## Sources with client loot tables ({ROLLS} rolls each, seed {SEED})")?;
    writeln!(md)?;
    writeln!(md, "| Id | Source | Drop | Rate |")?;
    writeln!(md, "|---:|---|---|---:|")?;
    for id in db.source_ids().into_iter().filter(|i| db.has_table_loot(*i)) {
        let mut counts: BTreeMap<i32, u32> = BTreeMap::new();
        for _ in 0..ROLLS {
            for d in db.roll(id, &mut rng)?.drops {
                *counts.entry(d.item_id()).or_default() += 1;
            }
        }
        let name = db.name(id).unwrap_or_default();
        for (item, n) in &counts {
            let iname = item_name.get(item).cloned().unwrap_or_default();
            writeln!(md, "| {id} | `{name}` | {item} {iname} | {:.1}% |", 100.0 * f64::from(*n) / f64::from(ROLLS))?;
        }
    }
    writeln!(md)?;
    writeln!(md, "## Fallback by source kind ({ROLLS} rolls per kind, seed {SEED})")?;
    writeln!(md)?;
    writeln!(md, "| Kind | Sources | Items per roll | Rotted | Normal | Uncommon | Enhanced | Epic | Legendary | Unique | Exceptional |")?;
    writeln!(md, "|---|---:|---:|---:|---:|---:|---:|---:|---:|---:|---:|")?;
    for (kind, ids) in &by_kind {
        let mut items = 0u32;
        let mut rar = [0u32; 8];
        for i in 0..ROLLS {
            for d in db.roll(ids[(i as usize) % ids.len()], &mut rng)?.drops {
                items += 1;
                if let Some(r) = db.rarity(&d) {
                    let n = r.number();
                    if (1..=8).contains(&n) {
                        rar[(n - 1) as usize] += 1;
                    }
                }
            }
        }
        let pct = |n: u32| if items == 0 { "—".to_string() } else { format!("{:.1}%", 100.0 * f64::from(n) / f64::from(items)) };
        write!(md, "| {kind:?} | {} | {:.2} |", ids.len(), f64::from(items) / f64::from(ROLLS))?;
        for n in rar {
            write!(md, " {} |", pct(n))?;
        }
        writeln!(md)?;
    }
    writeln!(md)?;
    writeln!(md, "## Source classification")?;
    for (kind, ids) in &by_kind {
        let names: Vec<String> = ids.iter().map(|i| format!("`{}`", db.name(*i).unwrap_or_default())).collect();
        writeln!(md)?;
        writeln!(md, "**{kind:?}** ({}): {}", ids.len(), names.join(", "))?;
    }
    std::fs::write(out, md).with_context(|| format!("writing {}", out.display()))?;
    println!("loot-doc: {} kinds -> {}", by_kind.len(), out.display());
    Ok(())
}
