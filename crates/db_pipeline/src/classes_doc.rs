//! `db_pipeline classes-doc`: writes from the config cache.

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;
use std::path::Path;

use anyhow::Context;
use db_formats::ConfigTables;
use db_sim::attributes::{CLASSES, class_sheet, class_type_id, starting_gear};

pub fn run(cache: &Path, out: &Path) -> anyhow::Result<()> {
    let tables: ConfigTables = serde_json::from_slice(
        &std::fs::read(cache.join("tables.json")).with_context(|| format!("reading {}/tables.json (run `db_pipeline config`)", cache.display()))?,
    )?;
    let strings: BTreeMap<String, BTreeMap<String, String>> = serde_json::from_slice(&std::fs::read(cache.join("strings.json"))?)?;
    let text = |k: &str| strings.values().find_map(|t| t.get(k)).cloned().unwrap_or_default();

    let mut ids = Vec::new();
    for c in CLASSES {
        ids.push((c, class_type_id(&tables, c)?));
    }
    let mut md = String::new();
    writeln!(md, "# Classes and base attributes")?;
    writeln!(md)?;
    writeln!(
        md,
        "Generated by `cargo run -p db_pipeline -- classes-doc` from `ExcelRoleType`, `ExcelRoleLevelUpgrade` and \
         `ExcelRoleDefaultEquipment` (CONFIRMED data). Code: `crates/db_sim/src/attributes.rs`. Do not edit by hand."
    )?;
    writeln!(md)?;
    writeln!(
        md,
        "Every class has levels 1–20. Attribute names are the protocol names with `affix_` (as in `ExcelBattleAttributeDescription`). \
         Values not set by a class are 0. HYPOTHESIS: how primary stats (strength, dexterity, stamina, intelligence, will, faith) \
         turn into derived stats is not in the client data."
    )?;
    writeln!(md)?;
    writeln!(md, "| Class | Type id | Name key | Source name |")?;
    writeln!(md, "|---|---:|---|---|")?;
    for (c, id) in &ids {
        let row = tables.excel_role_type.iter().find(|r| r.type_id == *id).context("class row")?;
        writeln!(md, "| {c:?} | {id} | `{}` | {} |", row.str_name, text(&row.str_name))?;
    }
    for level in [1, 20] {
        let sheets: Vec<_> = ids.iter().map(|(_, id)| class_sheet(&tables, *id, level)).collect::<Result<_, _>>()?;
        let keys: BTreeSet<&String> = sheets.iter().flat_map(|s| s.0.keys()).collect();
        writeln!(md)?;
        writeln!(md, "## Level {level}")?;
        writeln!(md)?;
        write!(md, "| Attribute |")?;
        for (c, _) in &ids {
            write!(md, " {c:?} |")?;
        }
        writeln!(md)?;
        writeln!(md, "|---|{}", "---:|".repeat(ids.len()))?;
        for k in keys {
            write!(md, "| `{}` |", k.trim_start_matches("affix_"))?;
            for s in &sheets {
                write!(md, " {} |", s.get(k))?;
            }
            writeln!(md)?;
        }
    }
    writeln!(md)?;
    writeln!(md, "## Starting equipment")?;
    writeln!(md)?;
    writeln!(md, "`ExcelRoleType.create_default_item_config_ids` → `ExcelRoleDefaultEquipment` (slot, item id × count). Item names come with S7.")?;
    writeln!(md)?;
    for (c, id) in &ids {
        let gear = starting_gear(&tables, *id)?;
        let list: Vec<String> = gear.iter().map(|g| format!("{:?} {}×{}", g.slot, g.item_id, g.count)).collect();
        writeln!(md, "- **{c:?}**: {}", list.join(", "))?;
    }
    std::fs::write(out, md).with_context(|| format!("writing {}", out.display()))?;
    println!("classes-doc: {} classes -> {}", ids.len(), out.display());
    Ok(())
}
